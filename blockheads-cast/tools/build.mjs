// Builds dist/builder.js (drop-in for render/builder.js) and dist/studio.html (single-file viewer).
import fs from 'fs'; import path from 'path';
const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..'); const r=p=>fs.readFileSync(path.join(root,p),'utf8');
const builder=r('src/builder.js'), cast=r('src/cast.js');
fs.writeFileSync(path.join(root,'dist/builder.js'),`/* Blockheads builder v2 + cast — generated by tools/build.mjs, edit src/ instead */\n${builder}\n${cast}\n`);
const thumbs=fs.existsSync(path.join(root,'dist/v1_thumbs.json'))?r('dist/v1_thumbs.json'):'{}';
let html=r('studio/studio.src.html').replace('/*@BUILDER@*/',()=>builder).replace('/*@CAST@*/',()=>cast).replace('/*@V1THUMBS@*/',()=>thumbs);
fs.writeFileSync(path.join(root,'dist/studio.html'),html);
const cj=new Function("BH",`${cast}\nreturn CAST;`)({});
fs.writeFileSync(path.join(root,'dist/cast.json'),JSON.stringify(cj,null,1));
console.log('dist/builder.js',(fs.statSync(path.join(root,'dist/builder.js')).size/1024).toFixed(0)+'KB','dist/studio.html',(html.length/1024).toFixed(0)+'KB','cast.json',cj.length,'characters');
